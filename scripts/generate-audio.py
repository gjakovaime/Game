def synth(model: VitsModel, tokenizer: AutoTokenizer, text: str, out_path: str) -> None:
    if os.path.exists(out_path):
        print(f"  skip  {os.path.basename(out_path)}")
        return
    inputs = tokenizer(text, return_tensors="pt").to(DEVICE)
    with torch.no_grad():
        waveform = model(**inputs).waveform[0].cpu().numpy()

    waveform_int16 = (np.clip(waveform, -1.0, 1.0) * 32767).astype(np.int16)
    wav_buf = io.BytesIO()
    scipy.io.wavfile.write(wav_buf, rate=model.config.sampling_rate, data=waveform_int16)
    wav_buf.seek(0)
    AudioSegment.from_wav(wav_buf).export(out_path, format="mp3", bitrate="96k")

    size = os.path.getsize(out_path)
    print(f"  ok    {os.path.basename(out_path)}  ({size // 1024} KB)")


def write_audio_files_ts() -> None:
    """Write src/data/audioFiles.ts with require() entries for every generated MP3."""
    ts_path = os.path.join(os.path.dirname(__file__), "..", "src", "data", "audioFiles.ts")
    lines = [
        "// Auto-generated by scripts/generate-audio.py — do not edit manually.",
        "// Run: docker compose --profile audio run --rm generate-audio",
        "// Then rebuild: docker compose exec game npm run build:web",
        "export const AUDIO_FILES: Record<string, number> = {",
    ]
    mapping = [
        ("words",     WORDS),
        ("sentences", SENTENCES),
        ("praises",   praises),
    ]
    for subdir, items in mapping:
        for file_id, text in items.items():
            mp3 = os.path.join(BASE, subdir, f"{file_id}.mp3")
            if os.path.exists(mp3):
                escaped = text.replace("'", "\\'")
                lines.append(f"  '{escaped}': require('../../assets/audio/{subdir}/{file_id}.mp3'),")
    lines.append("};")
    with open(ts_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"  wrote  src/data/audioFiles.ts  ({len(lines) - 4} entries)")


def main() -> None:
    print(f"Device: {DEVICE}")
    if DEVICE == "cpu":
        print("WARNING: No GPU detected — generation will be slow.")

    print(f"Loading {MODEL_ID} ...")
    model = VitsModel.from_pretrained(MODEL_ID).to(DEVICE)
    tokenizer = AutoTokenizer.from_pretrained(MODEL_ID)
    model.eval()
    print("Model ready.\n")

    sections = [("words", WORDS), ("sentences", SENTENCES), ("praises", praises)]
    for subdir, items in sections:
        label = subdir.capitalize()
        print(f"── {label} {'─' * (38 - len(label))}")
        out_dir = os.path.join(BASE, subdir)
        os.makedirs(out_dir, exist_ok=True)
        for file_id, text in items.items():
            synth(model, tokenizer, text, os.path.join(out_dir, f"{file_id}.mp3"))

    print("\n── audioFiles.ts ──────────────────────────")
    write_audio_files_ts()
    print("\nDone. Rebuild the web bundle: docker compose exec game npm run build:web")


if __name__ == "__main__":
    main()
