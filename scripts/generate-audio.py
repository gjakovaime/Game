DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
BASE = os.path.join(os.path.dirname(__file__), "..", "assets", "audio")

# Keys are the output filename (no extension).
# Values are the Albanian text to synthesize.
# Word keys must match the `albanian` field in src/data/vocabulary.ts exactly.

